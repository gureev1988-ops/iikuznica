"""Generate the Decider wheel lock using uv and PyPI metadata for the image's platform."""
import subprocess
import tomllib
from pathlib import Path
from tempfile import TemporaryDirectory


def main():
    directory = Path(__file__).resolve().parent
    with TemporaryDirectory() as temporary:
        resolution = Path(temporary) / "pylock.toml"
        subprocess.run([
            "uv", "pip", "compile", "--python-version", "3.12", "--python-platform", "x86_64-manylinux_2_28",
            "--only-binary", ":all:", "--exclude-newer", "2026-11-27T22:00:00Z",
            "--default-index", "https://pypi.org/simple", "--format", "pylock.toml",
            "--output-file", str(resolution), str(directory / "requirements.txt"),
        ], check=True, stdout=subprocess.DEVNULL)
        with resolution.open("rb") as result:
            packages = tomllib.load(result)["packages"]

    lines = ["# Generated by lock_requirements.py with uv 0.13.9 for CPython 3.12 on Linux/amd64."]
    for package in packages:
        hashes = sorted({wheel["hashes"]["sha256"] for wheel in package["wheels"]})
        if not hashes:
            raise ValueError(f"No compatible wheel for {package['name']}")
        flags = " ".join(f"--hash=sha256:{digest}" for digest in hashes)
        lines.append(f"{package['name']}=={package['version']} {flags}")
    (directory / "requirements.lock").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
